function isShowcaseAccountId(id) {
    if (!id) return false;
    const s = String(id).toLowerCase();
    if (s.startsWith('ff-showcase-') || s.startsWith('a0000001-ff')) return true;
    if (typeof WASEET_SHOWCASE_ACCOUNTS !== 'undefined' && Array.isArray(WASEET_SHOWCASE_ACCOUNTS)) {
        return WASEET_SHOWCASE_ACCOUNTS.some(acc => String(acc.id) === String(id) && (acc.isUnavailableOnEscrow || acc.isUnavailable));
    }
    return false;
}

if (typeof window !== 'undefined') {
    window.WASEET_SHOWCASE_ACCOUNTS = WASEET_SHOWCASE_ACCOUNTS;
    window.isShowcaseAccountId = isShowcaseAccountId;
}
